-- V1: esquema inicial (usuarios, animais, interesses).
-- Nunca edite uma migração já aplicada: mudanças futuras entram como V2__..., V3__...

CREATE TABLE usuarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL,
    senha_hash    VARCHAR(100) NOT NULL,
    telefone      VARCHAR(30)  NOT NULL,
    criado_em     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE animais (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(80)  NOT NULL,
    especie        VARCHAR(20)  NOT NULL,
    porte          VARCHAR(20)  NOT NULL,
    sexo           VARCHAR(10)  NOT NULL,
    idade          VARCHAR(40)  NOT NULL,
    cidade         VARCHAR(100) NOT NULL,
    descricao      TEXT         NOT NULL,
    saude          VARCHAR(200) NOT NULL,
    temperamento   VARCHAR(200),
    foto_url       VARCHAR(300),
    responsavel_id BIGINT       NOT NULL REFERENCES usuarios (id),
    destaque       BOOLEAN      NOT NULL,
    status         VARCHAR(15)  NOT NULL,
    criado_em      TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE interesses (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id             BIGINT       NOT NULL REFERENCES animais (id),
    nome                  VARCHAR(120) NOT NULL,
    cidade                VARCHAR(100) NOT NULL,
    email                 VARCHAR(150) NOT NULL,
    telefone              VARCHAR(30)  NOT NULL,
    moradia               VARCHAR(25)  NOT NULL,
    possui_outros_animais BOOLEAN      NOT NULL,
    motivo                TEXT         NOT NULL,
    criado_em             TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- Índices para as consultas do catálogo e do painel
CREATE INDEX idx_animais_responsavel ON animais (responsavel_id);
CREATE INDEX idx_animais_status ON animais (status);
CREATE INDEX idx_interesses_animal ON interesses (animal_id);
